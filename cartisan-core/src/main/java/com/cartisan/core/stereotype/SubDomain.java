package com.cartisan.core.stereotype;

/**
 * DDD 战略设计的子域类型。
 *
 * <p>这是一个完备分类：任何业务概念必然属于这三类之一。
 * 通过决策树可确定类型：</p>
 * <pre>
 * 这个领域能力是否构成业务核心竞争力？
 *   ├─ 是 → {@link #CORE}（核心域）
 *   └─ 否 → 是否业务流程必须有它？
 *       ├─ 是 → {@link #SUPPORTING}（支撑域）
 *       └─ 否 → {@link #GENERIC}（通用域）
 * </pre>
 *
 * @see BoundedContext
 * @since 0.1.0
 */
public enum SubDomain {
    /**
     * 核心域。
     *
     * <p>业务核心竞争力的来源，值得投入最优质的资源。
     * 核心域的差异化能力决定了公司在市场中的竞争地位。</p>
     *
     * <p>示例：电商平台的商品推荐算法、在线教育平台的自适应学习引擎。</p>
     */
    CORE,

    /**
     * 支撑域。
     *
     * <p>业务流程必须但非核心竞争力的能力。
     * 可以考虑外包、购买现成方案或使用开源组件。</p>
     *
     * <p>示例：用户认证、权限管理、消息通知。</p>
     */
    SUPPORTING,

    /**
     * 通用域。
     *
     * <p>所有行业都一样的通用能力，没有差异化价值。
     * 应直接使用现成方案，避免重复造轮子。</p>
     *
     * <p>示例：日志记录、文件存储、邮件发送、支付网关对接。</p>
     */
    GENERIC
}
